"""Integration tests for `mas backup` Db2 database name handling (ibm-mas/cli#2513)."""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from utils.backup_restore_test_helper import BackupRestoreTestConfig, runBackupRestoreTest  # noqa: E402

BASE_ARGV = [
    "--instance-id",
    "inst1",
    "--backup-version",
    "20260101-000000",
    "--backup-storage-class",
    "ibmc-file-gold-gid",
    "--backup-storage-access-mode",
    "ReadWriteMany",
    "--no-confirm",
]

MANAGE_ARGV = [
    "--backup-manage-app",
    "--manage-workspace-id",
    "ws1",
    "--backup-manage-db",
    "--manage-db2-namespace",
    "db2u",
    "--manage-db2-instance-name",
    "mas-inst1-ws1-manage",
    "--manage-db2-backup-type",
    "offline",
]

FACILITIES_ARGV = [
    "--backup-facilities-app",
    "--facilities-workspace-id",
    "ws1",
    "--backup-facilities-db",
    "--facilities-db2-namespace",
    "db2u",
    "--facilities-db2-instance-name",
    "mas-inst1-ws1-facilities",
]


def test_backup_non_interactive_without_dbname():
    """
    Given a non-interactive backup of Manage and Facilities with Db2 but no database name flags
    When the backup pipeline is launched
    Then no db2 dbname params are sent, so the pipeline/role default (BLUDB) applies
    """
    result = runBackupRestoreTest(BackupRestoreTestConfig(command="backup", argv=BASE_ARGV + MANAGE_ARGV + FACILITIES_ARGV))

    params = result.launchParams
    assert params is not None, "launchBackupPipeline was not called"
    assert params["mas_instance_id"] == "inst1"
    assert params["backup_version"] == "20260101-000000"
    assert params["backup_manage_db"] == "true"
    assert params["manage_db2_instance_name"] == "mas-inst1-ws1-manage"
    assert params["backup_facilities_db"] == "true"
    assert "manage_db2_dbname" not in params
    assert "facilities_db2_dbname" not in params


def test_backup_non_interactive_with_dbname():
    """
    Given a non-interactive backup with --manage-db2-dbname and --facilities-db2-dbname
    When the backup pipeline is launched
    Then the custom database names are passed through as pipeline params
    """
    argv = BASE_ARGV + MANAGE_ARGV + ["--manage-db2-dbname", "MAXDB"] + FACILITIES_ARGV + ["--facilities-db2-dbname", "TRIDB"]
    result = runBackupRestoreTest(BackupRestoreTestConfig(command="backup", argv=argv))

    params = result.launchParams
    assert params is not None, "launchBackupPipeline was not called"
    assert params["manage_db2_dbname"] == "MAXDB"
    assert params["facilities_db2_dbname"] == "TRIDB"
    assert params["manage_workspace_id"] == "ws1"
    assert params["facilities_workspace_id"] == "ws1"


def test_backup_interactive_prompts_for_dbname():
    """
    Given an interactive backup of Manage including its Db2 database
    When the user enters a custom Db2 database name at the prompt
    Then the database name is passed to the backup pipeline as manage_db2_dbname
    """
    promptHandlers = {
        ".*Proceed with this cluster.*": lambda msg: "y",
        ".*Use the auto-detected storage classes.*": lambda msg: "y",
        ".*Enter backup PVC storage size.*": lambda msg: "20Gi",
        ".*Use autogenerated backup_version.*": lambda msg: "y",
        ".*Include MongoDB in backup.*": lambda msg: "n",
        ".*Include SLS in backup.*": lambda msg: "n",
        ".*backup the Manage application.*": lambda msg: "y",
        ".*Use this workspace.*": lambda msg: "y",
        ".*include PVC backup for Manage.*": lambda msg: "y",
        ".*backup the Manage database.*": lambda msg: "y",
        ".*Enter Db2 namespace.*": lambda msg: "db2u",
        ".*Enter Db2 instance name.*": lambda msg: "mas-inst1-ws1-manage",
        ".*Enter Db2 database name.*": lambda msg: "MAXDB",
        ".*Select backup type.*": lambda msg: "1",
        ".*backup the Facilities application.*": lambda msg: "n",
        ".*upload the backup archive.*": lambda msg: "n",
        ".*Clean backup and config workspaces.*": lambda msg: "y",
        ".*Proceed with these settings.*": lambda msg: "y",
    }
    result = runBackupRestoreTest(BackupRestoreTestConfig(command="backup", prompt_handlers=promptHandlers))

    params = result.launchParams
    assert params is not None, "launchBackupPipeline was not called"
    assert params["mas_instance_id"] == "inst1"
    assert params["manage_workspace_id"] == "ws1"
    assert params["manage_db2_instance_name"] == "mas-inst1-ws1-manage"
    assert params["manage_db2_dbname"] == "MAXDB"
    assert params["manage_db2_backup_type"] == "offline"
    assert params["backup_facilities_db"] == "false"
    assert "facilities_db2_dbname" not in params
