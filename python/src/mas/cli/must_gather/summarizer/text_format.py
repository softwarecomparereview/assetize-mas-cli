"""Plain-text rendering of must-gather summary files.

Some IBM support tooling cannot render Markdown, so the summaries produced by the
summarizers can additionally (or instead) be written as plain-text files where
Markdown tables are converted to aligned text tables.
"""

import glob
import logging
import os
import re

from tabulate import tabulate

logger = logging.getLogger(__name__)

SUMMARY_FORMATS = ["md", "txt", "both"]

_LINK_PATTERN = re.compile(r"\[([^\]]*)\]\(([^)]*)\)")
_BOLD_PATTERN = re.compile(r"(\*\*|__)(.+?)\1")
_CODE_PATTERN = re.compile(r"`([^`]*)`")
_HEADING_PATTERN = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
_SEPARATOR_CELL_PATTERN = re.compile(r"^:?-{3,}:?$")
_PIPE_SPLIT_PATTERN = re.compile(r"(?<!\\)\|")


def _stripInline(text: str, keepLinkTargets: bool) -> str:
    """Remove inline Markdown markup (links, bold, inline code) from a string.

    Args:
        text (str): Markdown text
        keepLinkTargets (bool): Render links as "text (target)" rather than just "text"

    Returns:
        str: Plain text
    """
    if keepLinkTargets:
        text = _LINK_PATTERN.sub(lambda m: f"{m.group(1)} ({m.group(2)})" if m.group(2) else m.group(1), text)
    else:
        text = _LINK_PATTERN.sub(lambda m: m.group(1), text)
    text = _BOLD_PATTERN.sub(lambda m: m.group(2), text)
    text = _CODE_PATTERN.sub(lambda m: m.group(1), text)
    return text.replace("\\|", "|")


def _splitTableRow(line: str) -> list[str]:
    """Split a Markdown table row into its cells."""
    stripped = line.strip()
    if stripped.startswith("|"):
        stripped = stripped[1:]
    if stripped.endswith("|") and not stripped.endswith("\\|"):
        stripped = stripped[:-1]
    return [cell.strip() for cell in _PIPE_SPLIT_PATTERN.split(stripped)]


def _isSeparatorRow(cells: list[str]) -> bool:
    """Check whether a table row is the Markdown header separator (e.g. | --- | :--- |)."""
    return len(cells) > 0 and all(_SEPARATOR_CELL_PATTERN.match(cell) for cell in cells)


def _renderTable(rows: list[list[str]]) -> list[str]:
    """Render parsed Markdown table rows as an aligned plain-text table.

    Args:
        rows (list[list[str]]): Table rows, first row is the header when followed by a separator row

    Returns:
        list[str]: Lines of the rendered table
    """
    hasHeader = len(rows) > 1 and _isSeparatorRow(rows[1])
    if hasHeader:
        headers = rows[0]
        body = [row for row in rows[2:] if not _isSeparatorRow(row)]
    else:
        headers = ()
        body = [row for row in rows if not _isSeparatorRow(row)]

    headers = [_stripInline(cell, keepLinkTargets=False) for cell in headers]
    body = [[_stripInline(cell, keepLinkTargets=False) for cell in row] for row in body]
    rendered = tabulate(body, headers=headers, tablefmt="simple", disable_numparse=True)
    return rendered.splitlines()


def markdownToText(content: str) -> str:
    """Convert the Markdown used in must-gather summaries to plain text.

    Tables become aligned text tables, headings are underlined, and inline markup
    (links, bold, inline code) and code fences are removed.

    Args:
        content (str): Markdown content

    Returns:
        str: Plain-text content
    """
    output = []
    tableRows = []

    def flushTable():
        if tableRows:
            output.extend(_renderTable(tableRows))
            tableRows.clear()

    for line in content.splitlines():
        stripped = line.strip()

        if stripped.startswith("|"):
            tableRows.append(_splitTableRow(stripped))
            continue
        flushTable()

        if stripped.startswith("```"):
            # Drop code fences, keep their content
            continue

        headingMatch = _HEADING_PATTERN.match(stripped)
        if headingMatch:
            level = len(headingMatch.group(1))
            title = _stripInline(headingMatch.group(2), keepLinkTargets=True)
            output.append(title)
            if level == 1:
                output.append("=" * len(title))
            elif level == 2:
                output.append("-" * len(title))
            continue

        output.append(_stripInline(line, keepLinkTargets=True))

    flushTable()
    return "\n".join(output).rstrip() + "\n"


def findSummaryFiles(outputDir: str) -> list[str]:
    """List the Markdown summary files generated by the summarizers.

    Args:
        outputDir (str): Path to must-gather output directory

    Returns:
        list[str]: Paths to existing Markdown summary files
    """
    files = sorted(glob.glob(os.path.join(outputDir, "summaries", "*.md")))
    subscriptionsFile = os.path.join(outputDir, "resources", "_cluster", "subscriptions.md")
    if os.path.isfile(subscriptionsFile):
        files.append(subscriptionsFile)
    return files


def applySummaryFormat(outputDir: str, summaryFormat: str = "md") -> list[str]:
    """Write the summary files in the requested format.

    - md: leave the Markdown summaries untouched (default)
    - txt: write a plain-text .txt equivalent of each summary and remove the .md file
    - both: write a plain-text .txt equivalent alongside each .md summary

    Args:
        outputDir (str): Path to must-gather output directory
        summaryFormat (str): One of md, txt, both

    Returns:
        list[str]: Paths of the plain-text files written
    """
    if summaryFormat not in SUMMARY_FORMATS:
        raise ValueError(f"Unsupported summary format: {summaryFormat}. Valid formats: {', '.join(SUMMARY_FORMATS)}")
    if summaryFormat == "md":
        return []

    written = []
    for mdFile in findSummaryFiles(outputDir):
        txtFile = os.path.splitext(mdFile)[0] + ".txt"
        with open(mdFile, "r") as f:
            content = f.read()
        with open(txtFile, "w") as f:
            f.write(markdownToText(content))
        written.append(txtFile)
        if summaryFormat == "txt":
            os.remove(mdFile)
        logger.debug(f"Wrote plain-text summary {txtFile}")
    return written
